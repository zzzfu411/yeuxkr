function t(title, body, speak, ko, zh) {
  return { title, body, speak, examples: [{ ko, zh }] };
}
function c(prompt, answer, choices, explain) {
  return { type: "choice", prompt, answer, choices, explain };
}
function z(prompt, clozeText, answer, choices, explain) {
  return { type: "cloze", prompt, clozeText, answer, choices, explain };
}
function d(prompt, answer, speak, explain) {
  return { type: "dictation", prompt, answer, acceptable: [answer, `${answer}.`], speak, explain };
}

