import { readFileSync, writeFileSync } from 'node:fs';
import { allLessons } from '../src/data/lessons/index.js';

// The shared progress engine needs assessment and prerequisite data, not every lesson's teaching cards.
const runtime = allLessons.map(({ teach: _teach, ...lesson }) => lesson);
const source = '// Generated by npm run content:prepare. Edit src/data/lessons instead.\n/** @type {import("./types").RuntimeLesson[]} */\nexport const runtimeLessons = ' + JSON.stringify(runtime) + ';\n';
const path = new URL('../src/data/lessons/runtime.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== source) {
    console.error('Course runtime is stale. Run npm run content:prepare, then review the generated change.');
    process.exitCode = 1;
  }
} else writeFileSync(path, source);
