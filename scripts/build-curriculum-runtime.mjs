import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { allLessons } from '../src/data/lessons/index.js';
import { vocab } from '../src/data/lexicon.js';
import { grammarPoints } from '../src/data/grammar.js';

// The shared progress engine needs assessment and prerequisite data, not every lesson's teaching cards.
const runtime = allLessons.map(({ teach: _teach, ...lesson }) => lesson);
const runtimeSource = '// Generated by npm run content:prepare. Edit src/data/lessons instead.\n/** @type {import("./types").RuntimeLesson[]} */\nexport const runtimeLessons = ' + JSON.stringify(runtime) + ';\n';
const runtimePath = new URL('../src/data/lessons/runtime.generated.js', import.meta.url);

// Lightweight ID catalog keeps full lexicon (198 KB) and grammar (64 KB) out of the root layout bundle.
const catalogIdsSource =
  '// Generated by npm run content:prepare. Edit src/data/vocab or src/data/grammar instead.\n' +
  '/** @type {readonly string[]} */\n' +
  'export const vocabIds = ' + JSON.stringify(vocab.map((item) => item.id)) + ';\n' +
  '/** @type {readonly string[]} */\n' +
  'export const grammarIds = ' + JSON.stringify(grammarPoints.map((item) => item.id)) + ';\n';
const catalogIdsPath = new URL('../src/data/catalog-ids.generated.js', import.meta.url);

const artifacts = [
  { path: runtimePath, source: runtimeSource, label: 'Course runtime' },
  { path: catalogIdsPath, source: catalogIdsSource, label: 'Catalog ID index' }
];

if (process.argv.includes('--check')) {
  for (const artifact of artifacts) {
    if (!existsSync(artifact.path) || readFileSync(artifact.path, 'utf8') !== artifact.source) {
      console.error(`${artifact.label} is stale. Run npm run content:prepare, then review the generated change.`);
      process.exitCode = 1;
    }
  }
} else {
  for (const artifact of artifacts) {
    writeFileSync(artifact.path, artifact.source);
  }
}
