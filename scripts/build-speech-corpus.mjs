import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import ts from "typescript";

const repoRoot = process.cwd();
const sourceRoots = [join(repoRoot, "src", "data"), join(repoRoot, "src", "app"), join(repoRoot, "src", "components")];
const corpusPath = join(repoRoot, "scripts", "speech-corpus.json");
const generatedModulePath = join(repoRoot, "src", "data", "speech-assets.generated.js");
const publicManifestPath = join(repoRoot, "public", "assets", "audio", "ko", "manifest.json");
const directSpeechKeys = new Set(["speak", "ko", "korean", "result", "example", "source"]);
const nestedSpeechKeys = new Set(["dictation"]);
const literalSpeechMapNames = new Set(["HANGUL_SOUND_BY_ID"]);
const koreanPattern = /[\uac00-\ud7a3]/;
const values = new Set();

for (const root of sourceRoots) {
  for (const file of walk(root)) collectFromFile(file);
}

const jobs = [...values]
  .map(normalizeSpeechText)
  .filter(Boolean)
  .filter((text, index, all) => all.indexOf(text) === index)
  .sort((left, right) => left.localeCompare(right, "ko"))
  .map((text) => ({
    text,
    file: `${createHash("sha256").update(text).digest("hex").slice(0, 20)}.mp3`
  }));

mkdirSync(dirname(publicManifestPath), { recursive: true });
writeFileSync(corpusPath, `${JSON.stringify(jobs, null, 2)}\n`, "utf8");
writeFileSync(
  generatedModulePath,
  [
    "// Generated by scripts/build-speech-corpus.mjs. Do not edit manually.",
    `export const BUNDLED_SPEECH_ASSETS = Object.freeze(${JSON.stringify(Object.fromEntries(jobs.map((job) => [job.text, `/assets/audio/ko/${job.file}`])), null, 2)});`,
    ""
  ].join("\n"),
  "utf8"
);
writeFileSync(
  publicManifestPath,
  `${JSON.stringify({ voice: "vits-mimic3-ko_KO-kss_low", generatedAt: new Date().toISOString(), assets: jobs }, null, 2)}\n`,
  "utf8"
);

console.log(`Prepared ${jobs.length} Korean speech jobs from ${sourceRoots.map((root) => relative(repoRoot, root)).join(", ")}.`);

function collectFromFile(file) {
  const source = readFileSync(file, "utf8");
  const kind = extname(file) === ".tsx" ? ts.ScriptKind.TSX : extname(file) === ".ts" ? ts.ScriptKind.TS : ts.ScriptKind.JS;
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, kind);

  function visit(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && literalSpeechMapNames.has(node.name.text)) {
      collectDescendantStrings(node.initializer);
    }

    if (ts.isPropertyAssignment(node)) {
      const key = propertyName(node.name);
      if (directSpeechKeys.has(key)) collectDirectValue(node.initializer);
      if (nestedSpeechKeys.has(key)) collectDescendantStrings(node.initializer);
    }

    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      if (node.expression.text === "speakKorean") collectDirectValue(node.arguments[0]);
      if (node.expression.text === "speakSequence") collectDescendantStrings(node.arguments[0]);
    }

    ts.forEachChild(node, visit);
  }

  visit(tree);
}

function collectDirectValue(node) {
  if (node && (ts.isStringLiteralLike(node) || ts.isNoSubstitutionTemplateLiteral(node))) add(node.text);
}

function collectDescendantStrings(node) {
  if (!node) return;
  if (ts.isStringLiteralLike(node) || ts.isNoSubstitutionTemplateLiteral(node)) add(node.text);
  ts.forEachChild(node, collectDescendantStrings);
}

function add(value) {
  const text = normalizeSpeechText(value);
  if (text && koreanPattern.test(text)) values.add(text);
}

function normalizeSpeechText(value) {
  if (typeof value !== "string") return "";
  const text = value.normalize("NFC").replace(/\s+/g, " ").trim();
  return text && text.length <= 500 ? text : "";
}

function propertyName(name) {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text;
  return "";
}

function* walk(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if ([".js", ".ts", ".tsx"].includes(extname(entry.name))) yield path;
  }
}
